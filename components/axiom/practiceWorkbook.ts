export function resolveWorkbookId(value: string | null | undefined): WorkbookId {
  return practiceWorkbooks.some((book) => book.id === value) ? (value as WorkbookId) : 'book1';
}
export const workbookHref = (id: WorkbookId) =>
  `/preview/axiom-next-nbl-v2/practice-workbook?form=${id}#workbook-form`;
export function practiceWorkbookMarkdown(drafts: WorkbookDrafts, only?: WorkbookId): string {
  return [
    '# NBL 会議用ワークブック',
    '目標：障害のある人が、必要な支援とともに望む仕事と生活を選べること。比較する仕事の条件と、実行する担当・権限・有償時間・費用をつなぎます。',
    '画面内で記入したメモです。架空記入例は含めません。未記入は未確認であり、承認・実施・効果を意味しません。',
    ...practiceWorkbooks
      .filter((book) => !only || book.id === only)
      .flatMap((book) => [
        `\n## ${book.title}`,
        ...book.fields.map(
          (field) => `\n### ${field.label}\n${drafts[book.id]?.[field.id]?.trim() || '未記入'}`,
        ),
      ]),
    '\n本人の共有範囲と各担当の権限を確認して使います。必要な支援を記入の完了待ちにせず、実施・支払の自動承認には使いません。',
  ].join('\n');
}
