export function continuityCapacity(carryCount: number, carryHours: number, newTarget: number) {
  if (!Number.isInteger(carryCount) || !Number.isInteger(newTarget) ||
      ![carryCount, carryHours, newTarget].every(Number.isFinite) ||
      carryCount < 0 || carryCount > 1000 || carryHours < 0 || carryHours > 1600 ||
      newTarget < 0 || newTarget > 1000) throw new Error('invalid_capacity_assumptions');
  const availableHours = 2 * 1600 * 0.65;
  const otherHours = 80 * 4, reserveHours = 320, newHoursEach = 36;
  const carriedHours = carryCount * carryHours;
  const requiredHours = carriedHours + newTarget * newHoursEach + otherHours + reserveHours;
  return { availableHours, otherHours, reserveHours, carriedHours,
    newSlots: Math.max(0, Math.floor((availableHours - otherHours - reserveHours - carriedHours) / newHoursEach)),
    totalRequiredHours: requiredHours, shortageHours: Math.max(0, requiredHours - availableHours),
    totalFte: Math.ceil((requiredHours / (1600 * 0.65)) * 100) / 100 };
}

